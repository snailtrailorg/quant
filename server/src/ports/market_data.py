"""D32 端口 · 实时行情（batch 172a）。

只由 hub 进程内使用（D26 拓扑）；worker 消费 `hub:bars:*` 流，不直连行情端口。
"""

from __future__ import annotations

from typing import Callable, Protocol, runtime_checkable

from ..quant_common.domain import Tick


@runtime_checkable
class MarketDataPort(Protocol):
    # ── 生命周期（hub 主循环依赖） ────────────────────────────
    def connect(self, credentials: dict, params: dict) -> None: ...
    def close(self) -> None: ...
    @property
    def connected(self) -> bool: ...
    def start_ready(self) -> bool: ...
    def set_context(self, ctx: dict) -> None: ...
    def poll_supervise(self, trading_day: bool) -> None: ...   # 窗内 renew / 窗外 suspend
    def event_threads_healthy(self) -> bool: ...

    # ── 数据面 ────────────────────────────────────────────────
    def set_on_tick(self, cb: Callable[[Tick], None]) -> None: ...
    def subscribe(self, symbols: list[str]) -> None: ...
    def unsubscribe(self, symbols: list[str]) -> None: ...
    def snapshot(self, symbol: str) -> Tick | None: ...
